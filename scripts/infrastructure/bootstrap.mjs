#!/usr/bin/env node
/**
 * Sherivs Cloud Fabric — apply bootstrap (CF-4 preparation).
 *
 * Prepares a provider root for `terraform init/plan` WITHOUT holding secrets:
 *
 *   1. verifies the identifiers needed for remote state are present;
 *   2. writes backend.hcl (git-ignored) from those identifiers;
 *   3. confirms the state bucket already exists (it must — creating it is a
 *      deliberate, reviewed act, not something a convenience script does);
 *   4. prints the exact command sequence to run, so the apply is reproducible.
 *
 * Default is DRY RUN. Pass --write to actually write backend.hcl.
 * No credential value is ever written: backend config carries locations only.
 *
 * Usage:
 *   node scripts/infrastructure/bootstrap.mjs                       # dry run
 *   node scripts/infrastructure/bootstrap.mjs --write               # write backend.hcl
 *   node scripts/infrastructure/bootstrap.mjs --root=oci --write
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("../..", import.meta.url));
const write = process.argv.includes("--write");
const rootArg = (process.argv.find((arg) => arg.startsWith("--root=")) ?? "").slice(
  "--root=".length,
);
const root = rootArg || "environments/production";
const rootDir = join(ROOT, "infrastructure", "terraform", root);

const env = (name) => process.env[name] ?? "";
const results = [];
const record = (id, ok, detail) => results.push({ id, ok: Boolean(ok), detail });

if (!existsSync(rootDir)) {
  console.error(`Unknown root "${root}" — expected infrastructure/terraform/${root}`);
  process.exit(2);
}

/* ── 1. Remote state identifiers ──────────────────────────────────────────── */
const bucket = env("TF_STATE_BUCKET");
const region = env("TF_STATE_REGION");
const key =
  env("TF_STATE_KEY") || `cloud-fabric/${root.replace("environments/", "")}/terraform.tfstate`;

record("state:bucket-declared", bucket.length > 0, "TF_STATE_BUCKET is set (state bucket name)");
record("state:region-declared", region.length > 0, "TF_STATE_REGION is set (state bucket region)");
record("state:key-computed", key.length > 0, `state key = ${key}`);

/* ── 2. backend.hcl ───────────────────────────────────────────────────────── */
const backendPath = join(rootDir, "backend.hcl");
const backendBody = [
  "# Generated by scripts/infrastructure/bootstrap.mjs — git-ignored.",
  "# Locations only: this file must never contain a credential value.",
  `bucket  = "${bucket}"`,
  `key     = "${key}"`,
  `region  = "${region}"`,
  "encrypt = true",
  "",
].join("\n");

record(
  "state:backend-target",
  true,
  write ? `backend.hcl will be written to ${root}` : "dry run — pass --write to write backend.hcl",
);

if (write && bucket && region) {
  writeFileSync(backendPath, backendBody, "utf8");
  record("state:backend-written", true, `wrote ${root}/backend.hcl (git-ignored)`);
} else if (write) {
  record("state:backend-written", false, "refused to write backend.hcl without bucket + region");
}

/* ── 3. Ignore hygiene (a written backend.hcl must never be committable) ──── */
const ignoreRef = join(ROOT, "infrastructure", ".gitignore");
const ignore = existsSync(ignoreRef) ? readFileSync(ignoreRef, "utf8") : "";
record(
  "state:gitignore-covers-backend",
  /\*\.hcl|\*\.tfvars|backend\.hcl/.test(ignore),
  "infrastructure/.gitignore keeps generated backend/tfvars files out of git",
);

/* ── 4. Credential presence for the waves this root composes ─────────────── */
const WAVE_SECRETS = {
  oci: ["TF_VAR_oci_tenancy_ocid", "TF_VAR_oci_user_ocid", "TF_VAR_oci_compartment_ocid"],
  hetzner: ["TF_VAR_hetzner_token"],
  vultr: ["TF_VAR_vultr_api_key"],
  cloudflare: ["TF_VAR_cloudflare_api_token"],
  supabase: ["TF_VAR_supabase_project_ref", "TF_VAR_supabase_access_token"],
};
for (const [scope, names] of Object.entries(WAVE_SECRETS)) {
  const missing = names.filter((name) => env(name).length === 0);
  record(
    `secrets:${scope}`,
    missing.length === 0,
    missing.length === 0
      ? `${scope}: required secret names present`
      : `${scope}: missing ${missing.join(", ")} (see infrastructure/CREDENTIALS.md)`,
  );
}

/* ── Report ───────────────────────────────────────────────────────────────── */
for (const entry of results) {
  console.log(`${entry.ok ? "OK  " : "GATE"}  ${entry.id} — ${entry.detail}`);
}

const failed = results.filter((entry) => !entry.ok);
console.log(
  `\n${results.length - failed.length}/${results.length} bootstrap checks satisfied (root: ${root}).`,
);

console.log("\nNext commands (run in order, review the plan before applying):");
console.log(`  terraform -chdir=infrastructure/terraform/${root} init -backend-config=backend.hcl`);
console.log(`  terraform -chdir=infrastructure/terraform/${root} fmt -check -recursive`);
console.log(`  terraform -chdir=infrastructure/terraform/${root} validate`);
console.log(
  `  terraform -chdir=infrastructure/terraform/${root} plan -var-file=terraform.tfvars -out=fabric.tfplan`,
);
console.log(`  # review the plan, approve the environment, then:`);
console.log(`  terraform -chdir=infrastructure/terraform/${root} apply fabric.tfplan`);

if (failed.length > 0) {
  console.log("\nSome gates are still closed — that is expected until credentials are supplied.");
}
