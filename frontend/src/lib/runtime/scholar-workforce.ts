export const SCHOLAR_WORKFORCE_CODE_SET: ReadonlySet<string> = new Set(
  SCHOLAR_WORKFORCE_KINDS.map((k) => k.kindCode),
);

/** Resolve a Scholar workforce kind by code within the runtime:scholar catalog. */
export function scholarWorkforceKind(code: string): WorkforceKind | undefined {
  return workforceKindByCode(SCHOLAR_WORKFORCE_KINDS, SCHOLAR_RUNTIME_REF, code);
}

/** Display title of a position kind; undefined when the code is unknown. */
export function scholarWorkforceKindTitle(code: string): string | undefined {
  return scholarWorkforceKind(code)?.title;
}

/** Catalog grouping by family for pickers and HR surfaces. */
export function scholarWorkforceKindsByFamily(family: WorkforceFamily): WorkforceKind[] {
  return workforceKindsByFamily(SCHOLAR_WORKFORCE_KINDS, family);
}

/**
 * Legacy membership kind → canonical position-kind guidance. The legacy portal
 * membership kind (users.role) remains the P08 authorization signal; this
 * mapping only enriches display with the real African post title.
 */
const MEMBERSHIP_KIND_POSITION: Record<string, string> = {
  principal: "head_of_school",
  teacher: "subject_teacher",
  bursar: "bursar",
  driver: "driver",
};

export function scholarWorkforceKindForMembershipKind(
  membershipKind: string,
): WorkforceKind | undefined {
  const code = MEMBERSHIP_KIND_POSITION[membershipKind];
  return code ? scholarWorkforceKind(code) : undefined;
}
